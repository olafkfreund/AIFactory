"""Generate the autonomy matrix from the live merge policy (Factory#1962).

Every row is produced by CALLING ``merge.merge_policy`` / ``review_tier``;
nothing is transcribed, so the page cannot drift from the code.

Usage:
    python scripts/gen_autonomy_matrix.py --stdout   # print the markdown
"""

