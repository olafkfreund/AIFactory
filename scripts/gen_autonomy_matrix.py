# The exact inputs this generator probes. decide_merge gaining a parameter
# must fail loudly, not silently leave the matrix under-probed.
_PROBED_PARAMS = frozenset(
    {
        "tier",
        "host_ci_green",
        "tfactory_verdict",
        "achieved_val",
        "val_floor",
        "ci_parity",
        "deployment",
        "satisfied_gates",
    }
)

_VAL_PROBES: tuple[tuple[object, object], ...] = (
    (2, None),
    (2, ""),
    (2, "VAL-three"),
    (1, 2),
    (2, 2),
    (3, 2),
    (None, 2),
    ("VAL-2 (3 lanes)", 2),
)


def _check_signature() -> None:
    params = set(inspect.signature(mp.decide_merge).parameters)
    if params != _PROBED_PARAMS:
        extra = ", ".join(sorted(params - _PROBED_PARAMS)) or "(none)"
        missing = ", ".join(sorted(_PROBED_PARAMS - params)) or "(none)"
        print(  # noqa: T201
            f"decide_merge gained parameter {extra} (missing: {missing}); "
            "extend the probe set"
        )
        sys.exit(3)


def _tf(b: bool) -> str:
    return "T" if b else "F"


def _table(
    tabs: list[dict[str, object]], header: list[str], rows: list[list[str]]
) -> list[str]:
    tabs.append({"header": header, "rows": rows})
    out = [
        "| " + " | ".join(header) + " |",
        "|" + "|".join("---" for _ in header) + "|",
    ]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def _section_tiers(tabs: list[dict[str, object]]) -> tuple[list[str], int]:
    combos = list(
        itertools.product(
            (True, False), ("pass", "fail"), ((2, 1), (1, 2)), (True, False)
        )
    )
    rows: list[list[str]] = []
    for tier in sorted({*mp._TIER_ALIASES, "", "bogus"}):
        by_result: dict[str, list[str]] = {}
        for ci, verdict, (val, floor), parity in combos:
            result = mp.decide_merge(
                tier,
                host_ci_green=ci,
                tfactory_verdict=verdict,
                achieved_val=val,
                val_floor=floor,
                ci_parity=parity,
                deployment=None,
            )
            by_result.setdefault(result, []).append(
                f"ci={_tf(ci)} verdict={verdict} val={val}/{floor} parity={_tf(parity)}"
            )
        for result in sorted(by_result):
            conds = by_result[result]
            cell = "always" if len(conds) == len(combos) else "; ".join(conds)
            rows.append([f"`{tier}`" if tier else "`(blank)`", f"`{result}`", cell])
    lines = ["## A1. Tier decision (no deployment block)", ""]
    lines += _table(tabs, ["tier", "result", "when"], rows)
    return lines, len(rows)


def _section_overlay(tabs: list[dict[str, object]]) -> tuple[list[str], int]:
    seen: dict[tuple[tuple[str, ...], str], list[str]] = {}
    gate_sets = ([], ["security-scan"], ["human-approval", "security-scan"])
    for risk, prod, sat in itertools.product(
        ("high", "medium", "low", ""), ("production", "staging", "dev", ""), gate_sets
    ):
        dep = {
            "risk_class": risk,
            "production_classification": prod,
            "system_gates": ["human-approval", "security-scan"],
        }
        reasons = tuple(mp.deployment_block_reasons(dep, satisfied_gates=sat))
        result = mp.decide_merge(
            "low",
            host_ci_green=True,
            tfactory_verdict="pass",
            achieved_val=2,
            val_floor=1,
            ci_parity=True,
            deployment=dep,
            satisfied_gates=sat,
        )
        seen.setdefault((reasons, result), []).append(
            f"risk={risk or '-'} prod={prod or '-'} satisfied={','.join(sat) or '-'}"
        )
    rows = [
        [
            "<br>".join(r) if r else "(none)",
            f"`{result}`",
            f"{len(ex)} combos, e.g. {ex[0]}",
        ]
        for (r, result), ex in sorted(seen.items())
    ]
    lines = [
        "## A2. Deployment overlay (applied before the tier; all-green `low` change)",
        "",
        "Required gates: `human-approval`, `security-scan`.",
        "",
    ]
    lines += _table(tabs, ["block reasons", "result", "inputs"], rows)
    return lines, len(rows)


def _section_val(tabs: list[dict[str, object]]) -> tuple[list[str], int]:
    rows = [
        [f"`{a!r}`", f"`{f!r}`", str(mp._val_meets_floor(a, f))] for a, f in _VAL_PROBES
    ]
    lines = ["## A3. VAL floor semantics", ""]
    lines += _table(tabs, ["achieved", "floor", "meets floor"], rows)
    return lines, len(rows)


def _section_paths(tabs: list[dict[str, object]]) -> tuple[list[str], int]:
    patterns = review_tier.HIGH_RISK_PATTERNS
    probes = [*patterns, "README.md"]
    rows = [[f"`{p}`", f"`{mp.floor_from_paths([p])}`"] for p in probes]
    rows.append(["(no changed files)", f"`{mp.floor_from_paths([])}`"])
    lines = [
        "## A4. Path floor",
        "",
        "High-risk patterns: " + ", ".join(f"`{p}`" for p in patterns),
        "",
    ]
    lines += _table(tabs, ["changed path", "floor"], rows)
    return lines, len(rows)


