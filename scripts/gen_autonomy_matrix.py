@contextlib.contextmanager
def _env(**values: str | None) -> Iterator[None]:
    """Set (or, for None, remove) env vars; restore the originals on exit."""
    saved = {k: os.environ.get(k) for k in values}
    try:
        for k, v in values.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v
        yield
    finally:
        for k, v in saved.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v


def _section_wiring(tabs: list[dict[str, object]]) -> tuple[list[str], int]:
    from cli import workspace_commands as wc  # noqa: PLC0415

    lines = ["## B. Live wiring (pr_endgame)", ""]
    n = 0
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        # Blank vs low
        green = root / "green"
        green.mkdir()
        (green / "task_metadata.json").write_text(json.dumps(_GREEN_META))
        disp = {t: pe.merge_disposition(green, t) for t in (None, "", "low")}
        same = disp[None] == disp[""] == disp["low"]
        lines += ["### B1. Blank tier vs `low` (all-green signals)", ""]
        lines += _table(
            tabs,
            ["reviewTier", "disposition"],
            [[f"`{t!r}`", f"`{d}`"] for t, d in disp.items()],
        )
        lines += [""]
        lines += _table(tabs, ["check", "result"], [["blank == low", f"**{same}**"]])
        lines += [""]
        n += len(disp)

        # Unmeasured defaults
        empty = root / "empty"
        empty.mkdir()
        sig = pe.merge_gate_signals(empty)
        lines += ["### B2. Signals when nothing was measured", ""]
        lines += _table(
            tabs,
            ["signal", "default"],
            [[f"`{k}`", f"`{sig[k]!r}`"] for k in sorted(sig)],
        )
        lines += [""]
        n += len(sig)

        # Flag defaults
        names = {
            "auto-merge": (_AUTO_MERGE_ENV, pe.is_auto_merge_enabled),
            "path-floor enforcement": (pe.PATH_RISK_FLOOR_ENV, pe.path_floor_enforced),
        }
        rows = []
        for label, (env, fn) in sorted(names.items()):
            with _env(**{env: None}):
                unset = fn(None)
            with _env(**{env: "1"}):
                on = fn(None)
            rows.append([label, f"`{env}`", str(unset), str(on)])
        lines += ["### B3. Flags", ""]
        lines += _table(tabs, ["flag", "env var", "unset", 'set to "1"'], rows)
        lines += [""]
        n += len(rows)

        # Path floor, advisory vs enforced
        probe = review_tier.HIGH_RISK_PATTERNS[0]
        orig = wc._get_changed_files_from_git
        rows = []
        try:
            wc._get_changed_files_from_git = lambda *a, **k: [probe]
            for label, val in (("advisory (unset)", None), ("enforced (`1`)", "1")):
                spec = root / f"spec-{len(rows)}"
                spec.mkdir()
                with _env(**{pe.PATH_RISK_FLOOR_ENV: val}):
                    eff, floor = pe.apply_path_risk_floor(
                        root, spec, "probe", "dev", "low"
                    )
                rows.append([label, f"`{eff!r}`", f"`{floor!r}`"])
        finally:
            wc._get_changed_files_from_git = orig
        lines += [
            "### B4. Path floor on a `low` task touching "
            f"`{probe}`: (effective tier, floor)",
            "",
        ]
        lines += _table(tabs, ["enforcement", "effective tier", "floor"], rows)
        lines += [
            "",
            "Defaults shown; per-project settings and per-deployment env override them.",
        ]
        n += len(rows)
    return lines, n


# ---- Section C: gate determinism (ast import closure) ----------------------
_ROOTS = (_REPO_ROOT / "apps" / "backend", _REPO_ROOT / "apps" / "web-server")

# Importing any of these (or a submodule) makes a gate model-assisted.
_MODEL_CLIENTS = (
    "anthropic",
    "openai",
    "claude_agent_sdk",
    "google.genai",
    "ollama",
    "core.client",
    "core.simple_client",
    "providers",
)

_ENTRY_POINTS = (
    "merge.merge_policy",
    "server.services.pr_review_service",
    "server.services.pr_endgame",
)

# Minimum resolved local modules per entry point: floor(0.5 * measured).
# max(2, floor(0.5 * measured)); measured 2026-10-07: merge_policy 2,
# pr_review_service 263 (incl. runner via spawn edge), pr_endgame 352. A walk under its minimum means the
# prober is broken, and it must never emit a label.
_MIN_CLOSURE: dict[str, int] = {
    "merge.merge_policy": 2,
    "server.services.pr_review_service": 131,
    "server.services.pr_endgame": 176,
}

# DECLARED spawn edge, verified against the caller's source below.
# pr_review_service runs the reviewer as a subprocess, so its model client is
# invisible to a static import walk. extra_roots mirror the PYTHONPATH the
# service sets (backend + runners/github), so the runner's bare imports resolve.
_SPAWN_EDGES: dict[str, dict[str, object]] = {
    "server.services.pr_review_service": {
        "script": "apps/backend/runners/github/runner.py",
        "extra_roots": ["apps/backend/runners/github"],
    },
}

# DECLARED, not derived - cross-repo (PFactory / TFactory are not probed here).
_DECLARED_GATES = (
    ("PFactory", "plan/review/gates.py::run_gates"),
    ("TFactory", "apps/backend/agents/evaluator.py::_run_evaluator_session"),
)


def _find(name: str, roots: tuple[Path, ...] = _ROOTS) -> tuple[Path, bool] | None:
    """Resolve a dotted module name to (file, is_package) under *roots*."""
    rel = Path(*name.split("."))
    for root in roots:
        if (root / rel / "__init__.py").is_file():
            return root / rel / "__init__.py", True
        if (root / rel).with_suffix(".py").is_file():
            return (root / rel).with_suffix(".py"), False
    return None


def _closure(
    module_name: str, roots: tuple[Path, ...] = _ROOTS
) -> tuple[set[str], set[str]]:
    """Return (local modules walked, every imported name incl. third-party leaves)."""
    local: set[str] = set()
    names: set[str] = set()
    queue = [module_name]
    while queue:
        mod = queue.pop()
        if mod in local:
            continue
        found = _find(mod, roots)
        if found is None:
            continue
        path, is_pkg = found
        local.add(mod)
        pkg = mod if is_pkg else mod.rpartition(".")[0]
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                found_names = [a.name for a in node.names]
            elif isinstance(node, ast.ImportFrom):
                base = node.module or ""
                if node.level:
                    parts = pkg.split(".") if pkg else []
                    parts = parts[: len(parts) - (node.level - 1)]
                    base = ".".join([*parts, *([base] if base else [])])
                found_names = [base, *(f"{base}.{a.name}" for a in node.names)]
            else:
                continue
            for n in found_names:
                if not n:
                    continue
                names.add(n)
                if _find(n, roots):
                    queue.append(n)
    return local, names


def _verify_spawn_edge(
    caller: Path, edge: dict[str, object], repo: Path = _REPO_ROOT
) -> None:
    """Raise ValueError unless *caller*'s source still spawns the declared script."""
    tree = ast.parse(caller.read_text(encoding="utf-8"))
    strings = {n.value for n in ast.walk(tree) if isinstance(n, ast.Constant)}
    spawns = any(
        isinstance(n, ast.Call)
        and isinstance(n.func, ast.Attribute)
        and (
            n.func.attr == "create_subprocess_exec"
            or (isinstance(n.func.value, ast.Name) and n.func.value.id == "subprocess")
        )
        for n in ast.walk(tree)
    )
    script = repo / str(edge["script"])
    if not (
        {"runners", "github", "runner.py"} <= strings and spawns and script.is_file()
    ):
        raise ValueError(
            "spawn edge no longer matches its source - update _SPAWN_EDGES"
        )


def _entry_closure(entry: str) -> tuple[set[str], set[str], str]:
    """(local modules, imported names, spawn-edge label) for a gate entry point."""
    local, names = _closure(entry)
    edge = _SPAWN_EDGES.get(entry)
    if edge is None:
        return local, names, "-"
    found = _find(entry)
    try:
        if found is None:
            raise ValueError("caller not found")
        _verify_spawn_edge(found[0], edge)
    except ValueError as e:
        print(
            f"spawn edge for {entry} no longer matches its source - update _SPAWN_EDGES ({e})"
        )  # noqa: T201
        sys.exit(4)
    script = _REPO_ROOT / str(edge["script"])
    roots = (*_ROOTS, *(_REPO_ROOT / str(r) for r in edge["extra_roots"]))  # type: ignore[attr-defined]
    mod = ".".join(script.relative_to(_ROOTS[0]).with_suffix("").parts)
    sub_local, sub_names = _closure(mod, roots)
    return (
        local | sub_local,
        names | sub_names,
        f"`{script.relative_to(_REPO_ROOT / 'apps/backend')}`",
    )


def _hits(names: set[str]) -> list[str]:
    return sorted(
        c for c in _MODEL_CLIENTS if any(n == c or n.startswith(c + ".") for n in names)
    )


def _label(names: set[str]) -> str:
    return "model-assisted" if _hits(names) else "deterministic"


def _section_gates(tabs: list[dict[str, object]]) -> tuple[list[str], int]:
    rows = []
    for entry in _ENTRY_POINTS:
        local, names, via = _entry_closure(entry)
        if len(local) < _MIN_CLOSURE[entry]:
            print(  # noqa: T201
                f"prober resolved {len(local)} modules for {entry} "
                f"(min {_MIN_CLOSURE[entry]}) - refusing to label"
            )
            sys.exit(4)
        hit = _hits(names)
        rows.append(
            [
                f"`{entry}`",
                _label(names),
                ", ".join(f"`{h}`" for h in hit) or "-",
                str(len(local)),
                via,
            ]
        )
    lines = ["## C. Gate determinism (static import closure)", ""]
    lines += _table(
        tabs,
        ["gate", "label", "model clients imported", "local modules", "via spawn"],
        rows,
    )
    lines += ["", "Declared, unverified (cross-repo, not probed):", ""]
    lines += _table(tabs, ["repo", "gate"], [[r, f"`{g}`"] for r, g in _DECLARED_GATES])
    lines += [
        "",
        "`pr_endgame`'s review verdict is injected, not computed there; the review "
        "component is the separate `pr_review_service` row.",
    ]
    return lines, len(rows)


_SECTIONS = (
    ("tiers", _section_tiers),
    ("overlay", _section_overlay),
    ("val", _section_val),
    ("paths", _section_paths),
    ("wiring", _section_wiring),
    ("gates", _section_gates),
)

_OUT_MD = _REPO_ROOT / "docs" / "docs" / "compliance" / "autonomy-matrix.md"
_OUT_JSON = _REPO_ROOT / "docs" / "static" / "compliance" / "autonomy-matrix.json"
_FRONT_MATTER = f"---\ntitle: Autonomy matrix (generated)\ndraft: true\n---\n\n<!--\n{_GENERATED_BANNER}\n-->\n\n"


def build() -> tuple[str, str, dict[str, int]]:
    """Return (markdown, json text, row counts)."""
    _check_signature()
    out = ["# Autonomy matrix (generated)", ""]
    sections: list[dict[str, object]] = []
    counts: dict[str, int] = {}
    for key, fn in _SECTIONS:
        tabs: list[dict[str, object]] = []
        lines, counts[key] = fn(tabs)
        out += [*lines, ""]
        sections.append({"id": key, "title": lines[0].lstrip("# "), "tables": tabs})
    md = _FRONT_MATTER + "\n".join(out)
    js = json.dumps({"sections": sections}, indent=2, sort_keys=True) + "\n"
    return md, js, counts


def render() -> str:
    return build()[0]


def _first_diff(name: str, want: str, have: str) -> str:
    w, h = want.splitlines(), have.splitlines()
    for i in range(max(len(w), len(h))):
        a = w[i] if i < len(w) else "<eof>"
        b = h[i] if i < len(h) else "<eof>"
        if a != b:
            return f"{name}: line {i + 1} differs\n  generated: {a[:200]}\n  committed: {b[:200]}"
    return f"{name}: differs"


def check(md_path: Path = _OUT_MD, json_path: Path = _OUT_JSON) -> int:
    md, js, c = build()
    floors = {
        "tiers": (c["tiers"] >= 8),
        "overlay": (c["overlay"] >= 12),
        "val": (c["val"] == 8),
        "paths": (c["paths"] >= len(review_tier.HIGH_RISK_PATTERNS) + 2),
        "gates": (c["gates"] == 3),
    }
    bad = [k for k, ok in floors.items() if not ok]
    if bad:
        print(f"row-count minimum violated: {', '.join(bad)} ({c})")  # noqa: T201
        return 1
    for path, want in ((md_path, md), (json_path, js)):
        have = path.read_text(encoding="utf-8") if path.is_file() else ""
        if have != want:
            print(_first_diff(str(path), want, have))  # noqa: T201
            return 1
    print(  # noqa: T201
        f"ok: tiers={c['tiers']} overlay={c['overlay']} val={c['val']} "
        f"paths={c['paths']} gates={c['gates']}"
    )
    return 0


def main(
    argv: list[str] | None = None,
    *,
    md_path: Path = _OUT_MD,
    json_path: Path = _OUT_JSON,
) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stdout", action="store_true", help="Print the markdown.")
    parser.add_argument(
        "--check", action="store_true", help="Fail if outputs are stale."
    )
    args = parser.parse_args(argv)
    if args.check:
        return check(md_path, json_path)
    md, js, _ = build()
    if args.stdout:
        sys.stdout.write(md)
        return 0
    for path, text in ((md_path, md), (json_path, js)):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")  # noqa: T201
    return 0


if __name__ == "__main__":
    sys.exit(main())
